    <p align="center" style="font:16px times; color:#fff;">
    UNITED STATES PATENT OFFICE
    &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;
    &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;
    NIKOLA TESLA, OF NEW YORK, N.Y.<br />
    <br />
	COIL FOR ELECTRO-MAGNETS<br />
	<br />
	</p>
   
    <p>SPECIFICATION forming part of Letters Patent No. 512,340, dated January 9, 1894.</p>
    
    <p>Application filed July 7, 1893.  Serial No. 479,804.  (No model.)</p>
    
    <p>To all whom it may concern:</p>
    
    <p>
    Be it known that I, NIKOLA TESLA, a citizen of the United States,
    residing at New York, in the county and State of New York, have invented
    certain new and useful Improvements in Coils for Electro-Magnets and
    other Apparatus, of which the following is a specification, reference
    being had to the drawings accompanying and forming a part of the same.
    </p>
    <p>
    In electric apparatus or systems in which alternating currents are
    employed the self-induction of the coils or conductors may, and in fact,
    in many cases does operate disadvantagely by giving rise to false
    currents which often reduce what is known as the commercial efficiency
    of the apparatus composing the system or operate detrimentally in
    other respects.  The effects of self-induction, above referred to,
    are known to be neutralized by proportioning to a proper degree the
    capacity of the circuit with relation to the self-induction and
    frequency of the currents.  This has been accomplished heretofore
    by the use of condensers constructed and applied as separate instruments.
    </p>
    <p>
    My present invention has for its object to avoid the employment of
    condensers which are expensive, cumbersome and difficult to maintain
    in perfect condition, and to so construct the coils themselves as
    to accomplish the same ultimate object.
    </p>
    <p>
    I would here state that by the term coils I desire to include generally
    helices, solenoids, or, in fact, any conductor the different parts of
    which by the requirements of its application or use are brought into
    such relations with each other as to materially increase the self-induction.
    </p>
    <p>
    I have found that in every coil there exists a certain relation between
    its self-induction and capacity that permits a current of given frequency
    and potential to pass through it with no other opposition than that of ohmic
    resistance, or, in other words, as though it possessed no self-induction.
    This is due to the mutual relations existing between the special character
    of the current and the self-induction and capacity of the coil, the latter
    quantity being just capable of neutralizing the self-induction for that
    frequency.  It is well-known that the higher the frequency or potential
    difference of the current the smaller the capacity required to
    counteract the self-induction; hence, in any coil, however small the
    capacity, it may be sufficient for the purpose stated if the proper
    conditions in other respects be secured.  In the ordinary coils the
    difference of potential between adjacent turns or spires is very small,
    so that while they are in a sense condensers, they possess but very
    small capacity and the relations between the two quantities,
    self-induction and capacity, are not such as under any ordinary
    conditions satisfy the requirements herein contemplated, because the
    capacity relatively to the self-induction is very small.
    </p>
    <p>
    In order to attain my object and to properly increase the capacity
    of any given coil, I wind it in such way as to secure a greater difference
    of potential between its adjacent turns or convolutions, and since the
    energy stored in the coil considering - the latter as a condenser, is
    proportionate to the square of the potential difference between its
    adjacent convolutions, it is evident that I may in this way secure by
    a proper disposition of these convolutions a greatly increased capacity
    for a given increase in potential difference between the turns.
    </p>
    <p>
    I have illustrated diagrammatically in the accompanying drawings the
    general nature of the plan which I adopt for carrying out this invention.
    </p>
    <p>
    <strong>Figure 1</strong> is a diagram of a coil wound in the ordinary manner.<br>
    <strong>Figure 2</strong> is a diagram of a winding designed to secure the objects
    of my invention.
    </p>
    <p>
    Let A, <strong>Figure 1</strong>, designate any given coil the spires or convolutions of
    which are wound upon and insulated from each other.  Let it be assumed
    that the terminals of this coil show a potential difference of one hundred
    volts, and that there are one thousand convolutions; then considering any
    two contiguous points on adjacent convolutions let it be assumed that
    there will exist between them a potential difference of one-tenth of a volt.
    <br>
    <br>
    If now, as shown in <strong>Figure 2</strong>, a conductor B be wound parallel with the
    conductor A and insulated from it, and the end of A be connected
    with the starting point of B, the aggregate length of the two conductors
    being such that the assumed number of convolutions or turns is the same, viz.,
    one thousand, then the potential difference between any two points in
    A and B will be fifty volts, and as the capacity effect is
    proportionate to the square of this difference,<br>
    <strong>the energy stored in the coil as a whole will now be two hundred and fifty thousand as great</strong>.  
    <br>
    <br>
    Following out this principle, I may wind any given coil either in whole or in part, not only
    in the specific manner herein illustrated, but in a great variety of ways,
    well-known in the art, so as to secure between adjacent convolutions
    such potential difference as will give the proper capacity to neutralize
    the self-induction for any given current that may be employed.  Capacity
    secured in this particular way possesses an additional advantage in that
    it is evenly distributed, a consideration of the greatest importance in
    many cases, and the results, both as to efficiency and economy, are the
    more readily and easily obtained as the size of the coils, the potential
    difference, or frequency of the currents are increased.
    </p>
    <p>
    Coils composed of independent strands or conductors wound side by side
    and connected in series are not in themselves new, and I do not regard
    a more detailed description of the same as necessary.  But heretofore,
    so far as I am aware, the objects in view have been essentially different
    from mine, and the results which I obtain even if an incident to such
    forms of winding have not been appreciated or taken advantage of.
    </p>
    <p>
    In carrying out my invention it is to be observed that certain facts are
    well understood by those skilled in the art, viz: the relations of capacity,
    self-induction, and the frequency and potential difference of the current.
    What capacity, therefore, in any given case it is desirable to obtain and
    what special winding will secure it, are readily determinable from the other
    factors which are known.
    </p>
    <p>
    What I claim as my invention is:
    <ol>
      <li>A coil for electric apparatus the adjacent convolutions of which form
          parts of the circuit between which there exists a potential difference
          sufficient to secure in the coil a capacity capable of neutralizing its
          self-induction, as herein before described.
      </li>
    <br><br>
      <li>A coil composed of contiguous or adjacent insulated conductors
          electrically connected in series and having a potential difference
          of such value as to give to the coil as a whole, a capacity sufficient
          to neutralize its self-induction, as set forth.
      </li>
    </ol>
    </p>
    <h3>NIKOLA TESLA</h3>
    <p>
    Witnesses:
    <ul>
      <li>Robt. F. Gaylord
      </li>
      <li>Parker W. Page
      </li>
    </ul>
    </p>
