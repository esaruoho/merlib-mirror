<center><p class=graybar>Tesla's History In Colorado Springs, Colorado 1899-1900</p></center>
<br>
<table align="center" width=640>
<tr><td valign="top" class=bdytxt>

<font color="#FFffff" size="3" face="Times New Roman, Times, serif"><em>
Nikola Tesla arrived in Colorado Springs on May 17, 1899.<br></em></font>
<br>

<font color="#bbdddd" style="font:12px verdana;">
He was met at the train by patent lawyer Leonard Curtis, and was taken by horse and carriage to the Alta Vista Hotel, where he would reside while in Colorado. Tesla was greeted at the hotel by a group of reporters, one of whom asked him why he chose Colorado for his operation. Tesla replied, "<font class=quote>I might as well tell you the truth, I have come here to carry on a series of exhaustive experiments in regard to wireless telegraphyI come here for work."</font> The reporter asked if he was going to "<font class=quote>flash (his) message from Pike's Peak to Long's Peak or another mountain of Colorado?"</font> The question appeared to irritate Tesla who tersely replied, <font class=quote>"No, I am here to work. It is not pleasure. I am very busy and life is short and there is a great deal to be done."</font> 
<br><br>
Tesla ended the interview and retired to his room, #207. It was extremely important to Tesla that the room number be divisible by 3, a long running superstition. He also liked the fact that the room was only up one story and riding the elevator would be unnecessary. Although the hotel had excellent maid service, Tesla requested extra linens and 18 clean towels a day, saying he liked to do his own dusting. This germ phobia, which began in his youth, would grow more and more demanding as the years passed by.
<br><br>
Journalists reported that Tesla seemed to be distracted by more important thoughts than answers to their questions. Perhaps he was anxious for his assistant and equipment to arrive in Colorado Springs so he could begin his work. Because Tesla arrived a few days ahead of his assistant Lowenstein, there was time for important people of the local society to entertain Tesla at places such as The El Paso Club, an all men's club downtown. For a creative exploration into the mind of Tesla while he awaited Lowenstein's arrival.
<br><br>
By 1899, Tesla's ideas and experiments were far too large for his New York laboratory. Many of his general plans had already been pirated and he could not risk any more losses due to spy activity. He longed for open space and privacy. After secretly searching the country for the best location for his new lab, Tesla decided on Colorado Springs. This decision was based on many factors, the foremost being free land and electricity from the Colorado Springs Electric Company. Tesla also discovered that the area was ideal for conducting electrical experiments as well as observing the immense electrical storms of the region.
<br>
<br>
<font color="#FFFFFF" face="Times New Roman, Times, serif" size="3">Tesla later wrote,</font><br>
<font class="style3">The conditions in the pure air of the Colorado Mountains proved extremely favorable for my experiments, and the results were most gratifying to me. I found that I could not only accomplish more work, physically and mentally, than I could in New York, but that electrical effects and changes were more readily and distinctly perceived.</font>
<br>
<br>
Tesla and his assistants started construction of the new lab shortly after arriving in Colorado Springs. Aided by local contractor Joseph Dozier, they broke ground in the prairie land approximately one mile east of downtown, on Knob Hill. The land was located near the Colorado School for the Deaf and the Blind, which still operates to this day. Tesla's plan was to build a large barn like building, 50ft by 60ft with 18ft ceilings. From the center of the roof would protrude a 200ft pole fashioned with a 30" wooden ball covered in copper foil. It was within these walls that Tesla would attempt to accomplish three goals: 
<br><br>
<font class=title2> 
1 - To develop a transmitter of great power.<br> 
2 - To perfect a means for individualizing and isolating the energy transmitted.<br> 
3 - To ascertain the laws of propagation of currents through the earth's atmosphere.<br>
</font>
<br>
<br>
<div align="center" style="font:16px verdana; color:#ffffff;">Simply put,<br>
Tesla was attempting to provide free energy to all of Earth's people,<br>
without the use of wires!</div>
<br>
July 3, 1899 brought much excitement to the region. Planned Independence Day festivities included a gigantic display of pyrotechnics on the Summit of Pike's Peak. Town officials had brought 35,000 pounds of powder flares to the summit in hopes that the red white and blue flames would be visible as far away as Cheyenne, Wyoming. Unfortunately for the townspeople, but not for Tesla, Mother Nature had different plans. An immense storm of thunder and lightning struck the region, disappointing the crowds waiting for festivities. Tesla, on the other hand, was absolutely mesmerized. He made one of his most important discoveries, the existence of stationary waves within the earth, during the massive storm. As the storm began to form, Tesla quickly prepared his instruments. He observed the storm's formation and later wrote: 
<br><br>
&nbsp;&nbsp;&nbsp;&nbsp;<font class=quote>" A violent storm broke loose after spending much of its fury in the mountains. It was driven away with great velocity over the plains. Heavy and long persisting arcs formed almost in regular time intervals. My observations were now greatly facilitated and rendered more accurate by the experiences already gained. I was able to handle my instruments quickly and I was prepared. The recording apparatus being properly adjusted, its indications became fainter and fainter with the increasing distance of the storm until they ceased altogether. I was watching in eager expectation. Surely enough the indications began again, grew stronger and stronger, and, after passing through a maximum gradually decreased and ceased once more. Many times, in regularly recurring intervals, the same actions were repeated until the storm which, as evident in simple computations, was moving with nearly constant speed, had retreated to a distance of about 300 kilometers. Nor did these strange actions stop then, but continued to manifest themselves with undiminished force. Subsequently, similar observations were made by my assistant, Mr. Fritz Lowenstein, and shortly afterward several admirable opportunities presented themselves which brought out still more forcibly and unmistakably, the true nature of the wonderful phenomenon. No doubt whatever remained; I was observing stationary waves."</font>
<br><br>
This discovery convinced Tesla not only that wireless transmission of telegraphic messages was possible. Tesla also realized that he could transmit unlimited amounts of power to the entire globe, without the need for wires! Years later Tesla elaborated in a famous article in Century Magazine. 
<br><br>
&nbsp;&nbsp;&nbsp;&nbsp;<font class=quote>"Stationary waves in the earth mean something more than mere telegraphy without wires to any distance. They will enable us to attain many important specific results impossible otherwise. For instance, by their use we may produce at will, from a sending-station, an electrical effect in any particular region of the globe; we may determine the relative position or course of a moving object such as a vessel at sea, the distance traversed by the same, or its speed; or we may send over the earth a wave of electricity traveling at any rate we desire, from the pace of a turtle up to lightning speed."</font>
<br><br>
Tesla spent the next few months deeply submerged in his experimentation. Robert Underwood Johnson, a close friend of Tesla's, once wrote about the great inventor, <font class=quote>"Common people must have rest like machinery but the great old Nick - the Busy One- see him go 150 hours without food or drink. Why he can invent with his hands tied behind his back!"</font> The inventor would conduct many of his experiments at night, filling the dry mountain air with an eerie electric charge. In one particular experiment, Tesla successfully powered two hundred 50-watt lamps with electricity thrust through the ground. He accomplished this feat without the use of any wire connections, a full 26 miles from his laboratory! He also made the claim that this was possible at any distance, anywhere on the globe. On more than one occasion Tesla's experiments would start small fires in his lab. Once, he was even trapped in a barrage of electric streamers, forcing him to crawl on his belly to safety. Amazingly, these were far from his most dramatic or dangerous experiments. 
<br><br>
It was mid autumn when Tesla sent for another assistant, Kolman Czito. Tesla's head assistant, Fritz Lowenstein, was away in Germany on family matters and Tesla needed help with what was to become his most magnificent experiment ever: the creation of lightning! 
<br><br>
Sporting cotton balls in their ears and rubber soled shoes on their feet; Tesla and Czito would produce the largest display of man-made lightning to this day. After setting up cold lamps all over the area Tesla signaled Czito to close the switch until told to open it. The earth shook with the intensity of the mighty apparatus. Horses, regularly calm, reared up onto hind legs and ran frantically in all directions. According to Hunt and Draper, one pair of Tesla biographers, 
<br><br>
&nbsp;&nbsp;&nbsp;&nbsp;<font class=quote>"The crackling and snap repeated and then came a tremendous upsurge of sound as the power built up. There was a crescendo of vicious snaps above. The noises became machine-gun staccato, then roared to artillery intensity. Ghostly sparks danced a macabre routine all over the laboratory. There was a smell of sulfur that might be coming from hell itself. A weird blue light spread all over the room. Flames began to jump from the ball at the top of the mast- first a few feet long- then longer and brighter- thicker, bluer. More emanations until they reached rod like proportions thick as an arm and with a length of over 130 feet. The heavens reverberated with a terrific thunder that could be heard 15 miles over the ridge to Cripple Creek."</font> 
<br><br>
Then, without warning, the terrific force suddenly fell silent. The power was gone. Frantically, Tesla called the Colorado Springs Electric Company, demanding they restore his power and not interrupt his experiments, only to find he had destroyed their generator, causing it to erupt in flames. Once home to the largest generator this side of the Mississippi, Colorado Springs was now engulfed in darkness. Fortunately for the town they had a backup generator, but company officials denied Tesla access. He could receive electricity again, if and only if, he repaired the original generator at his own expense. The generator was working again in only a few short days. 
<br><br>
Tesla left Colorado Springs on January the 7th, 1900, never to return. His laboratory was later dismantled and its contents sold to pay outstanding debts. Although Tesla only spent 8 months in Colorado, it was in this crisp mountain town where he would make his most important discoveries. 
<br><br>
Tesla continued to invent for many years after leaving Colorado. He passed away on January 7, 1943 at the age of eighty-six. Despite Tesla's life of accomplishment and over seven hundred patents, his final days were spent living in near poverty at a second rate hotel. Upon hearing of the great inventors death, Eleanor Roosevelt wrote, <font class=quote>"The President and I are deeply sorry to hear of the death of Mr. Nikola Tesla. We are grateful for his contribution to science and industry and to this country."</font> Over 2,000 people attended the great inventor's funeral.<br>
<br>
Tesla's ashen remains have been stored in a splendid golden sphere<br>
at the <a href="http://www.yurope.com/org/tesla/muzeje.htm" target="_blank">Nikola Tesla Museum</a> in Belgrade since 1957. 
</font><br><br></p>
