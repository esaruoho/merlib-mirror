<div align="center" style="font:18px arial;">Shoreham, NY Hamlet Study, July 2002</div>
<p>
<font style="font:12px arial;">
<strong>3.2 TESLA PROPERTY, c. 1901</strong><br>
<br>
The Nikola Tesla Laboratory, most recently known as the Peerless Photo Plant, is  located between Randall Road to the west and Tesla Street to the east, and between  North Country Road to the north and Route 25A to the south (Figure 3).&nbsp;
The original brick building was designed by famed architect, Stanford White and financed by J.P. Morgan.  It was intended as the location of Tesla's prototype station for the World  Broadcasting System.  Dr. Nikola Tesla, a Croatian electrical engineer who immigrated  to the US in 1884, was not only the inventor of the Alternating Current (AC) electrical supply system, fluorescent lighting, the Tesla induction motor, and the Tesla coil, but also the acknowledged inventor of the radio.&nbsp;
A 1943 Supreme Court decision invalidated Marconi's radio patents because of Tesla's prior work.&nbsp;
Stanford White's associate, W.D. Crow, designed the 187-foot dome-capped tower for the laboratory, but the project was never
finished due to insufficient funding.&nbsp; In 1917 the property was foreclosed and the tower destroyed.&nbsp;
The laboratory and its former "tower" were not only designed to transmit radio signals but also the wireless transmission of power.&nbsp;
In fact, Tesla's "wonder tower" was the first transmission tower in the world.<br>
<br>
During the remainder of the 20th century the Tesla property was used for a variety of industrial activities, most
recently for the preparation of photographic emulsions.&nbsp; Significant soil contamination has occurred as a result (Sec. 4.7.1 ).&nbsp;
Access to the property is
currently controlled by a security guard.&nbsp; Any future use awaits the final cleanup of this contamination.<br>
<br>
The property is currently zoned L3 Industry (planned Industrial Park).&nbsp; Although this zoning category requires three-acre lots, Industrial zoning is inappropriate for this area.&nbsp;
We recommend that the Town rezone it to A2 Residential as a protective measure.&nbsp;
Following the cleanup and release of the site, the parcel should be developed to include a cultural center and science museum at the former Tesla laboratory.&nbsp;
The remainder of the property should be used for attached single-family homes or owner-occupied condominiums.&nbsp;
This proposal is discussed in greater detail in Sec. 5.2.3.<br>
<br>
<br>
<strong>4.7.1 Terrestrial Resources</strong><br>
<br>
A second known area of soil contamination is the site of the former Peerless Photo Plant (the Tesla property, Figure 3).&nbsp;
This 16-acre site was used for many years for preparation of photographic emulsions.&nbsp;
These activities discharged wastewater into on-site recharge basins and resulted in a number of areas of environmental concern.&nbsp;
Contamination in soil and groundwater has been detected during investigations sponsored
by the NYSDEC.&nbsp; This location has been identified by New York State as a Hazardous Waste Disposal Site and has been undergoing review and investigation since 1993.&nbsp;
The NYSDEC is currently awaiting an environmental report prepared by AGFA, the current owner, evaluating the cleanup options for this site.  The report was scheduled for completion during the spring of 2002, but was delayed following detection of contamination in the soil at greater depths than expected.&nbsp;
The report will be completed following additional soil testing, at which time the NYSDEC will propose fInal cleanup plans for the site.&nbsp;
A public comment period will be scheduled for review of these proposed actions.  AGFA is now in discussions with potential buyers who would remediate and then develop the site.&nbsp;
The NYSDEC should ensure that the site is cleaned up to residential standards.&nbsp;<br>
<br>
<strong>Recommendations</strong></p>
<ul>
<li>The NYSDEC should require soil cleanup to residential standards at the site of the former Peerless Photo Plant to permit future residential and recreational use.</li>
</ul>

<p>
<br>
<strong>5.2.3 Tesla (Peerless Photo) Property</strong><br>
<br>
The historic and environmental aspects of the Tesla site are discussed in detail in Sections 3.2 and 4.7.1.&nbsp;
The property was recently rezoned from L-1 Industry including the frontage 0-4) to the current L-3 (planned Industrial Park).&nbsp;<br>
<br>
Although in general the survey results pointed to a "keep things as they are" mentality, this was not the case with the Peerless Photo property.&nbsp;
Over 41 percent of the respondents preferred to see the property converted to a cultural use.  Some commercial use was suggested by 33 percent, and professional was cited by 25 percent.&nbsp;
Many survey comments mentioned the Tesla site as an opportunity for conversion to public space, such as a focal point for a town center.&nbsp;<br>
<br>
The location of the Tesla site near the center of Shoreham makes future industrial use undesirable.&nbsp;
This parcel should be rezoned A-5 Residence as a holding action and cleaned up to residential standards.&nbsp;
Once the cleanup of the site is completed, the property should be developed for mixed cultural and residential use.&nbsp;<br>
<br>
The historical significance of the former Tesla laboratory and its associated buildings is valued not only by Shoreham, but by neighboring communities as well and is considered to be of international significance.4  It is important that this piece of Shoreham's history be preserved.&nbsp;
The property is ideally situated to serve a cultural function.&nbsp;
It is located at the westerly end of Shoreham's commercial area on the main highway and has adequate space for museum parking with an entrance off a side road.&nbsp;
It abuts the LIP A right-of-way that is currently under consideration as a pedestrian and bicycle pathway, so it will be accessible to non-automobile traffic as well.&nbsp;
Stores in the commercial area along Rte. 25A would offer restaurants and shopping to those visiting the museum.&nbsp;
If funding can be secured, the historic Tesla laboratory should become a science museum.&nbsp;
Much of the groundwork for this proposal has already been laid by Friends of Science East.&nbsp;
A community activity/meeting center could be associated with the museum.&nbsp;<br>
<br>
A museum and cultural center would not require all the available space on the Peerless property.&nbsp;
Several options have been suggested by various organizations for use of the remainder of the property.&nbsp;
We recommend that it be used for two-story owner-occupied town homes or condominiums and/or for single-family residences on small (1/3 - 1/2 acre) lots.&nbsp;
This would provide additional housing options in the community, add density to the hamlet center, and offer proximity to shopping and services to people such as young families and the elderly who might want to live in a smaller residence.</p>


