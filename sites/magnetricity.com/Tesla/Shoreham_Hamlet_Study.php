<p><strong>Shoreham Hamlet Study Update, March 6, 2004</strong><br>
<br>
<strong>CHANGES SINCE THE 2002 HAMLET STUDY</strong><br>
<br>
<strong>2.1 ZONING CHANGES</strong>
</p>

<ul>
<li>The Tesla (Peerless Photo) Property, zoned L Industry 3
    in 2002, has been upzoned to A Residence 2.&nbsp; The Hamlet Study
    recommended A Residence 5 (five-acre residential) zoning as a protective
    mechanism until the completion of environmental cleanup at the site.</li>
</ul>

<p><strong>2.6 TESLA (PEERLESS PHOTO) PROPERTY</strong><br>
<br>
In addition to its recent up-zoning (Section 2.1), sampling and characterization of
contaminated soils and groundwater at the site of the former Tesla Laboratory have been completed.&nbsp;
The NYSDEC has prepared a Proposed Remedial Action Plan (PRAP) for cleanup at the site and public comment has been solicited.&nbsp;
Cleanup is expected to be completed in about two years (2006).&nbsp;
The PRAP meets the Hamlet Study recommendation for cleanup to residential guidelines in all but two locations on the site.&nbsp;
While both the zoning change and the proposed cleanup guidelines are in accordance with the intent of the Hamlet Study recommendations, and no acquisition can be accomplished until the cleanup is complete, more can and should be done to preserve this historic site for future public use.&nbsp;
The Town should consider creating a new zoning district for institutional and municipal uses and should apply it to the Tesla site.&nbsp;
Such a district would be transitional between Residential and Business districts and would serve as the "holding" category for which A-5 and A-10 Residential districts are now used.&nbsp;
Permitted uses would include schools, cultural centers, and other public uses.<br>
<br>
Because of its location between Rte. 25A and the planned Rails for Trails along the UPA right-of-way and its proximity to the Post Office and Shoreham Plaza, the Tesla property should, if possible, be dedicated in its entirety to public uses after cleanup.&nbsp;
However, as indicated in the Hamlet Study (SHS, p. 56), if economic or other conditions preclude transfer of the entire Tesla site to the Town (or other public entity), a limited number of residential units on the site would be acceptable.&nbsp;
Because the property is in the heart of the "hamlet center" that is part of the community's vision for its future, such residential development should be seamlessly integrated into the community as a whole.<br>
<br>
<br>
<strong>FOLLOW-UP RECOMMENDATIONS</strong>
</p>

<ul>
<li>The Tesla property should be dedicated to public use as a historic and cultural center.</li>
<li>The Shoreham 9/11 memorial should be relocated to this site.</font></li>
</ul>
