<div style="font:18px times; font-style:italic; color:#33ff33; border:1px solid #669966; background-color:#2c4400; padding:2px 0px 3px 0px;">
&nbsp;&nbsp;General Magnetricity<span class=red> 101</span></div>

<ul>
	<li>Similarities which scientists observed between electricity and magnetism led them to suggest that magnetic properties are possibly the result of forces between electric charges in motion.<br></li>
	<li>Substances which can be induced to become magnetized in a magnetic field are called&nbsp;&nbsp;<strong>Ferromagnetic</strong>.<br>
	<b>Soft Ferromagnetic</b> materials become demagnetized spontaneously when removed from a magnetic field.<br>
	<b>Hard Ferromagnetic</b> materials can retain their magnetism,	making them useful in the production of permanent magnets.<br></li>
	<li>A compass is a magnet which can align itself within the earth's magnetic field.<br></li>
	<li>A magnet contains a north-seeking pole (north pole) and a south-seeking pole (south pole).<br>
	(The possibility of having a single monopole is being investigated.)<br></li>
	<li>Similar magnetic poles repel. Opposite magnetic poles attract. (Law of Magnetic Poles)<br></li>
	<li>A magnetic field is a region in space where a magnetic force can be detected.<br></li>
	<li>The magnetic field is strongest at the poles of a magnet.<br></li>
	<li>Magnetic lines of force are a way of representing a magnetic field.<br></li>
	<li>By convention, magnetic lines of force point from north to south outside a magnet<br>
	and from south to north inside a magnet.<br></li>
	<li>Magnetic lines of force form complete loops. They never cross.<br></li>
	<li>The magnetic poles of the earth are not located at the geographic poles.<br>
	The angle between the geographic North Pole and the magnetic "north" pole <br>
	is called the magnetic declination.<br></li>
	<li>The angle of declination depends on one's location on earth.<br></li>
	<li>The earth's magnetic field does not run parallel to the earth's surface.<br>
	The angle of magnetic dip is the measure from the horizontal plane to the magnetic lines of force.<br>
	This also varies depending on one's position on the surface of the earth.<br></li>
	<li>The angle of magnetic dip is very large in the vicinity of the earth's magnetic poles,<br>
	making navigation difficult.<br></li>
	<li>The earth's magnetic field moves very slightly over long periods of time.<br>
	Plate tectonics may help to account for this phenomenon.<br></li>
	<li>Ore bodies in the Earth can influence the strength of the Earth's magnetic field.<br></li>
	<li>The units for magnetic field strength are the weber/m2, called the <strong>TESLA</strong>.<br>
	More familiar units representing the same thing are N/(A.m)</li>
</ul>

<br>
<br>
<div style="font:18px times; font-style:italic; color:#33ff33; border:1px solid #669966; background-color:#2c4400; padding:2px 0px 3px 0px;">
&nbsp;&nbsp;General Magnetricity<span class=red> 102</span></div>

<ul>
	<li class=yel>Materials attracted by magnets: <strong>Paramagnetic</strong></li>
	<li class=yel>Materials repelled by magnets: <strong>Diamagnetic</strong></li>
	<li class=yel>Materials which spontaneously form magnetized domains: <strong>Ferromagnetic</strong></li>
	<li class=yel>Materials in which neighboring spins like to align opposite to each other: <strong>Antiferromagnetic</strong></li>
	<br>
	<br>
	<li>Rust and corrosion strongly affect the magnetic properties of metals.<br>Ferromagnetic metals like iron in which interactions between the electrons of neighboring atoms tend to make their little bits of magnetism point in the same direction, forming magnetic domains. In a magnetic field, these domains line up with the field making a strong magnet.<br></li>
	<li>Other common ferromagnetic metals are nickel, and cobalt. Some of the strongest magnets are made with <strong>Neodymium</strong>. In some materials, the domains can get stuck so the material stays magnetized even when the field is removed, leaving a permanent magnet, but that usually involves introducing some non-magnetic components.</li>
	<li>Rusting and corrosion introduce atoms of other elements (typically oxygen), making new chemical forms with different interactions between neighboring atoms' electrons. Usually these end up either non-ferromagnetic or less ferromagnetic than the pure magnetic metal.</li>
	<li>There are several different oxides of iron, with different fractions of oxygen.<br>
	They are <b>Fe0</b>, <b>Fe2O3</b>, and <b>Fe3O4</b>.<br>

	<li>There are several forms of <b>Fe2O3</b>,<br>
	and a common mineral composed of <b>Fe2O3</b> is called Hematite, which is a shiny-blackish mineral.<br>
	Rust consists mostly of <b>Fe2O3</b>, with additional water molecules attached.</li>

	<li><strong>Hematite</strong> is not ferromagnetic,<br>
	but it does still respond to a magnetic field and will be attracted to the poles of a permanent magnet.<br></li>
	<li>Hematite itself has the interesting property of being nearly antiferromagnetic, in which the spinning electrons producing magnetic fields in neighboring atom groups like to align opposite to one another, canceling their fields out. This isn't perfect in hematite, with a small tip, or "canting" of the spins so that they don't cancel exactly, hence the attraction to the poles of a permanent magnet. I suspect that the addition of water molecules in ordinary orangey-yellow rust does not help the material become more magnetic than its Hematite cousin, but it's hard to be less magnetic than an antiferromagnet. <br></li>

	<li><b>FeO</b> is also not ferromagnetic,<br>
	but it is pulled about twice as much as <b>Fe2O3</b> towards the poles of a magnet.<br></li>

	<li><strong>Magnetite</strong>, <b>Fe3O4</b>, is ferromagnetic, and is about 1/4 as strong as pure iron.<br></li>
	<li>One warning is that rust may be a collection of the different oxides quite possibly other contaminants.<br>
	In particular, there may be bits of unrusted iron left in a sample of rust,<br>
	and these would be attracted very strongly to a magnet.</li>
	<li>Some substances change the signs of their response entirely when they corrode.<br>
	For instance, aluminum is very weakly attracted to the poles of magnets,<br>
	while aluminum oxide is very weakly repelled by the poles of magnets.</li>
	<li>Only ferromagnets are useful for making permanent magnets.<br>
	<strong>Paramagnetic</strong> and <strong>Diamagnetic</strong> forces tend to be very weak,<br>
	except for the diamagnetism of superconductors, which is strong enough to levitate them.</li>
	<li>U.S. nickels contain rather little nickel -- they are about 75% copper, and only 25% nickel.<br>
	This alloy seems to be not very magnetic. Older pure nickel nickels stick to magnets.<br>
	Pennies are 97.5% zinc with a thin coating of copper on the outside.</li>
	<li>Some steels (steel is mostly made of iron) are more magnetic than others.</li>
	<li>Two suggestions of things that can affect your experiments:</li>
	<li><strong>1)</strong>&nbsp;&nbsp;Rust and corrosion usually only occur in a very thin layer of the material near the surface. The rest of the material will be just as magnetic as it ever was, just minus the rusty layer. You may not notice any effect of the rust if most of the material is intact.</li>
	<li><strong>2)</strong>&nbsp;&nbsp;The shape and orientation of the metal object is very important in determining how strongly it will be attracted to a magnet. Be sure that the shapes of your uncorroded and corroded objects are the same when you compare their magnetic attraction or you could have other effects confusing the results.<br></li>
	<li>Tom J. and Mike W.&nbsp;...&nbsp;<a href="http://van.hep.uiuc.edu/van/qa/section/Electricity_and_Magnets/Magnets/20020512030401.htm">Link</a></li>
</ul>

